// Check placeholders
const checkPlaceholders = (valEn, valTr, keyName) => {
  if (typeof valEn === 'string') {
    const phEn = (valEn.match(/\{[a-zA-Z0-9_]+\}/g) || []).sort();
    const phTr = (valTr.match(/\{[a-zA-Z0-9_]+\}/g) || []).sort();
    assert.deepEqual(phTr, phEn, `Placeholder mismatch in ${keyName}: expected ${phEn}, got ${phTr}`);
  } else if (Array.isArray(valEn)) {
    valEn.forEach((item, idx) => checkPlaceholders(item, valTr[idx], `${keyName}[${idx}]`));
  } else if (typeof valEn === 'object' && valEn) {
    for (const [subK, subV] of Object.entries(valEn)) {
      checkPlaceholders(subV, valTr[subK], `${keyName}.${subK}`);
    }
  }
};

enKeys.forEach(k => {
  checkPlaceholders(en[k], hi[k], `HI.${k}`);
  checkPlaceholders(en[k], mr[k], `MR.${k}`);
});

